import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'C:/Users/PARAG PANDE/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base=process.env.CACHED_TEST_URL||'http://127.0.0.1:3213';
const data=await(await fetch(base+'/api/data')).json();
const {analysis}=await(await fetch(base+'/api/opportunities/opp-001')).json();
const saved={...analysis,provider:'OpenAI live',recommendation:{title:'Review customer approval',rationale:'Resolve the recorded evidence gap.',draft:'A saved follow-up draft for the customer.'},live:{runId:'cached-ui-test',model:'gpt-5-mini',generatedAt:'2026-10-20T10:00:00Z',inputHash:'cached-fixture',promptVersion:'test',summary:'Cached customer evidence remains available without generating a new result.',limitations:[],usage:{inputTokens:50,outputTokens:20,totalTokens:70}}};
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXE||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),aiRequests=[],errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/\/api\/(analyze|ai\/status)(?:\?|$)/.test(new URL(r.url()).pathname))aiRequests.push(r.url());});
 await page.route('**/api/data',r=>r.fulfill({json:{...data,actions:[],audit:[],liveAnalyses:{'opp-001':saved}}}));
 await page.goto(base+'/opportunities/opp-001');
 await page.getByRole('heading',{name:'Aster Manufacturing',exact:true}).waitFor();
 assert.equal(await page.locator('.live-analysis-control').count(),0,'Remove the entire live-analysis card');
 assert.equal(await page.getByRole('button',{name:/Run live analysis/}).count(),0);
 await page.getByText(saved.live.summary,{exact:true}).waitFor();
 await page.getByRole('button',{name:'Refresh evidence',exact:true}).click();
 await page.getByRole('button',{name:'Evidence refreshed',exact:true}).waitFor();
 await page.getByText(saved.live.summary,{exact:true}).waitFor();
 assert.doesNotMatch(await page.locator('body').innerText(),/\bbuyers?\b/i);
 await page.getByRole('button',{name:'View source: Budget is approved'}).click();
 await page.getByRole('dialog',{name:'Source evidence'}).waitFor();
 assert.doesNotMatch(await page.getByRole('dialog',{name:'Source evidence'}).innerText(),/\bbuyers?\b/i);
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Review follow-up',exact:true}).click();
 assert.equal(await page.getByLabel('Follow-up draft').inputValue(),saved.recommendation.draft);
 await page.keyboard.press('Escape');
 await page.screenshot({path:'.cache/cached-analysis-desktop.png'});
 await page.goto(base+'/guide');
 await page.getByRole('heading',{name:'Walk through DealSignal in five minutes'}).waitFor();
 assert.doesNotMatch(await page.locator('body').innerText(),/\bbuyers?\b/i);
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(aiRequests,[],'Browsing saved results must make no generation or AI-configuration requests');
 assert.deepEqual(errors,[]);
 console.log('PASS: no live-analysis card or AI requests; saved assessment and draft preserved; customer wording, source inspection, guide and mobile layout work');
} finally {await browser.close();}
